function storedLocale(): Locale | undefined {
  try {
    const value = localStorage.getItem(STORAGE_KEY);
    return value === 'en-US' || value === 'pt-BR' ? value : undefined;
  } catch {
    return undefined;
  }
}

let currentLocale: Locale = storedLocale() ?? 'en-US';

export function getLocale() { return currentLocale; }

export function setLocale(locale: Locale) {
  currentLocale = locale;
  try { localStorage.setItem(STORAGE_KEY, locale); } catch { /* Storage can be unavailable in privacy mode. */ }
}

export function t(key: string, values: Record<string, string | number> = {}) {
  const template = translations[currentLocale][key] ?? translations['en-US'][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function stageTitle(stage: number) { return t(`stage.${stage}.title`); }
export function stageObjective(stage: number) { return t(`stage.${stage}.objective`); }
export function enemyName(kind: 'scout' | 'assault' | 'elite') { return t(`enemy.${kind}`); }
export function bossSubsystemName(kind: 'turret' | 'shield' | 'engine' | 'reactor') { return t(`boss.${kind}`); }
export function bossObjective(phase: number) { return t(`boss.objective.${phase}`); }
export function formatScore(score: number) { return score.toLocaleString(currentLocale); }
